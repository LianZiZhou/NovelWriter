/**
 * Minimal i18n: English strings are the keys; other languages map them.
 * The app root is keyed by language, so a language switch re-renders everything.
 */
import { ZH_EXTRA } from './i18n-zh-extra.ts';
import { ZH_EMBEDDINGS } from './i18n-zh-embeddings.ts';
import { ZH_NLP } from './i18n-zh-nlp.ts';
import { ZH_DIRECTOR } from './i18n-zh-director.ts';

export type Lang = 'en' | 'zh';

let lang: Lang = 'en';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
}

export function getLang(): Lang {
  return lang;
}

/** Translate, with `{name}` interpolation. */
export function t(s: string, vars?: Record<string, string | number>): string {
  let out = lang === 'zh' ? (ZH[s] ?? s) : s;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

